export type ErrorParams = Record<string, string | number | boolean | null | string[] | Record<string, unknown>[]>;

/** Business-rule failure thrown by shared and backend domain code. */
export class DomainError extends Error {
  constructor(
    readonly code: ErrorCode,
    readonly params: ErrorParams = {},
  ) {
    super(code);
    this.name = 'DomainError';
  }
}
